import { Link, useRouter, type Href } from 'expo-router';
import { useState } from 'react';
import { Alert, ScrollView, StyleSheet, Text, View } from 'react-native';
import { useSafeAreaInsets } from 'react-native-safe-area-context';

import { AppError } from '@/src/domain/errors';
import { durationMinutes } from '@/src/domain/time';
import { errorMessage, strings } from '@/src/strings';
import { useActiveWorkout } from '@/src/ui/ActiveWorkoutContext';
import { Button } from '@/src/ui/components/Button';
import { useNow } from '@/src/ui/useNow';

// Cast: typed-routes types (.expo/types, git-ignored) are generated by expo start and may be stale.
const WORKOUT_ROUTE = '/workout' as Href;
const HISTORY_ROUTE = '/history' as Href;
const EXERCISES_ROUTE = '/exercises' as Href;

export default function Home() {
  const router = useRouter();
  const { active, workoutService, settingsService, refresh } = useActiveWorkout();
  const [starting, setStarting] = useState(false);
  const now = useNow();
  const insets = useSafeAreaInsets();

  async function start() {
    if (starting) return;
    setStarting(true);
    try {
      // D14: the first workout start asks for notification permission. It runs before
      // startWorkout so the reminder scheduled by the start (R1) already has permission.
      await settingsService.requestPermissionOnFirstWorkout();
      await workoutService.startWorkout();
      await refresh();
      router.push(WORKOUT_ROUTE);
    } catch (e) {
      // WORKOUT_ALREADY_ACTIVE (double tap / stale state): reload and show the Resume card.
      await refresh();
      if (!(e instanceof AppError && e.code === 'WORKOUT_ALREADY_ACTIVE')) {
        Alert.alert(strings.home.startFailed, e instanceof AppError ? errorMessage(e.code) : '');
      }
    } finally {
      setStarting(false);
    }
  }

  return (
    <ScrollView
      style={styles.scroll}
      contentContainerStyle={[styles.container, { paddingBottom: 24 + insets.bottom }]}
    >
      <Text style={styles.title}>{strings.home.title}</Text>
      {active === undefined ? null : active ? (
        <View style={styles.card}>
          <Text style={styles.cardTitle}>
            {strings.home.resumeTitle} · {durationMinutes(active.started_at, now)}{' '}
            {strings.workout.minutes}
          </Text>
          <Button title={strings.home.resume} onPress={() => router.push(WORKOUT_ROUTE)} />
        </View>
      ) : (
        <Button title={strings.home.startWorkout} onPress={() => void start()} disabled={starting} />
      )}
      <Link href={HISTORY_ROUTE} style={styles.link}>
        {strings.home.history}
      </Link>
      <Link href={EXERCISES_ROUTE} style={styles.link}>
        {strings.home.exercises}
      </Link>
      {__DEV__ ? (
        <Link href="/dev-check" style={styles.link}>
          {strings.home.deviceCheck}
        </Link>
      ) : null}
    </ScrollView>
  );
}

const styles = StyleSheet.create({
  scroll: { flex: 1 },
  container: { flexGrow: 1, alignItems: 'center', justifyContent: 'center', padding: 24, gap: 16 },
  title: { fontSize: 32, fontWeight: '700' },
  card: {
    alignSelf: 'stretch',
    gap: 12,
    padding: 16,
    borderRadius: 12,
    borderWidth: 1,
    borderColor: '#ccc',
  },
  cardTitle: { fontSize: 18, fontWeight: '600', textAlign: 'center' },
  link: { fontSize: 18, color: '#0a7ea4', padding: 12 },
});
